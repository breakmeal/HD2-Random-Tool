import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';

const ROOT=path.resolve(import.meta.dirname,'..');
const OUTPUT=path.join(ROOT,'equipment-descriptions-zh.js');
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));

async function loadSource(){
  const context={};
  vm.createContext(context);
  const data=await fs.readFile(path.join(ROOT,'data.js'),'utf8');
  const details=await fs.readFile(path.join(ROOT,'equipment-details.js'),'utf8');
  vm.runInContext(`${data};globalThis.__GEAR=GEAR;`,context);
  vm.runInContext(`${details};globalThis.__DETAILS=EQUIPMENT_DETAILS;`,context);
  return {gear:context.__GEAR,details:context.__DETAILS};
}

async function loadExisting(){
  try{
    const source=await fs.readFile(OUTPUT,'utf8');
    const context={};
    vm.createContext(context);
    vm.runInContext(`${source};globalThis.__ZH=EQUIPMENT_DESCRIPTIONS_ZH;`,context);
    return context.__ZH||{};
  }catch(error){
    if(error.code==='ENOENT')return {};
    throw error;
  }
}

function normalizeTranslation(value){
  return String(value||'')
    .replace(/地狱潜水员/g,'绝地潜兵')
    .replace(/地狱舱舱/g,'地狱舱')
    .replace(/超级地球武装力量/g,'超级地球武装部队')
    .replace(/终结族/g,'虫族')
    .replace(/自动机/g,'机器人')
    .replace(/光明会/g,'光能者')
    .replace(/策略装备/g,'战略配备')
    .replace(/战略装备/g,'战略配备')
    .replace(/战争债券/g,'战争债券')
    .replace(/\s+/g,' ')
    .trim();
}

async function translate(text,retries=5){
  const url=new URL('https://translate.google.com/translate_a/single');
  Object.entries({client:'gtx',sl:'en',tl:'zh-CN',dt:'t',q:text}).forEach(([key,value])=>url.searchParams.set(key,value));
  for(let attempt=0;attempt<retries;attempt++){
    try{
      const response=await fetch(url,{headers:{'user-agent':'Mozilla/5.0'}});
      if(!response.ok)throw new Error(`${response.status} ${response.statusText}`);
      const raw=await response.text();
      if(!raw)throw new Error('translator returned an empty response');
      const payload=JSON.parse(raw);
      const translated=normalizeTranslation(payload?.[0]?.map(part=>part?.[0]||'').join(''));
      if(!/[\u3400-\u9fff]/.test(translated))throw new Error('response did not contain Chinese text');
      return translated;
    }catch(error){
      if(attempt===retries-1)throw error;
      await sleep(800*(attempt+1));
    }
  }
}

async function mapPool(items,worker,concurrency=3){
  const results=new Array(items.length);
  let cursor=0;
  const workers=Array.from({length:concurrency},async()=>{
    while(cursor<items.length){
      const index=cursor++;
      results[index]=await worker(items[index],index);
      await sleep(140);
    }
  });
  await Promise.all(workers);
  return results;
}

const {gear,details}=await loadSource();
const existing=await loadExisting();
const pending=gear.filter(item=>!/[\u3400-\u9fff]/.test(existing[item.id]||''));
console.log(`Translating ${pending.length} of ${gear.length} equipment descriptions...`);
const translated=await mapPool(pending,async(item,index)=>{
  const source=details[item.id]?.officialDescription;
  if(!source)throw new Error(`${item.id}: missing officialDescription`);
  const value=await translate(source);
  if((index+1)%20===0||index===pending.length-1)console.log(`${index+1}/${pending.length}`);
  return [item.id,value];
});

const map={...existing,...Object.fromEntries(translated)};
const missing=gear.filter(item=>!/[\u3400-\u9fff]/.test(map[item.id]||''));
const orphan=Object.keys(map).filter(id=>!gear.some(item=>item.id===id));
if(missing.length||orphan.length)throw new Error(`translation validation failed: missing=${missing.length}, orphan=${orphan.length}`);
const ordered=Object.fromEntries(gear.map(item=>[item.id,map[item.id]]));
const output=`/* Generated by scripts/generate-chinese-descriptions.mjs from the English source text in equipment-details.js. */\nconst EQUIPMENT_DESCRIPTIONS_ZH = ${JSON.stringify(ordered,null,2)};\n`;
await fs.writeFile(OUTPUT,output,'utf8');
console.log(JSON.stringify({equipment:gear.length,translated:Object.keys(ordered).length,missing:missing.length,orphan:orphan.length},null,2));
